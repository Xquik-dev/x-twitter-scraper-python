from __future__ import annotations

from pathlib import Path
from datetime import date

import pytest

from tests.utils import json_dumps
from scripts.verify_audit import main

TODAY = date(2026, 10, 13)
AUDITED = """# This file was autogenerated by uv.
anyio==4.14.2 \\
    --hash=sha256:aa
pytest==9.0.1 \\
    --hash=sha256:bb
Pygments==2.20.0 ; python_full_version >= '3.10' \\
    --hash=sha256:cc
"""
RUNTIME = """anyio==4.14.2 \\
    --hash=sha256:aa
"""


def finding(advisory: str, fixes: list[str], aliases: list[str] | None = None) -> dict[str, object]:
    return {"id": advisory, "fix_versions": fixes, "aliases": aliases or [], "description": "Long text."}


def dependencies(**vulns: list[dict[str, object]]) -> list[dict[str, object]]:
    versions = {"anyio": "4.14.2", "pytest": "9.0.1", "pygments": "2.20.0"}
    return [{"name": name, "version": version, "vulns": vulns.get(name, [])} for name, version in versions.items()]


def report(**vulns: list[dict[str, object]]) -> dict[str, object]:
    return {"dependencies": dependencies(**vulns), "fixes": []}


def exception(**overrides: object) -> dict[str, object]:
    entry: dict[str, object] = {
        "id": "GHSA-dev1-0000-0000",
        "package": "pytest > pygments",
        "reason": "build-time only",
        "recheck": "2026-11-12",
    }
    entry.update(overrides)
    return entry


def run(tmp_path: Path, audit_report: object, exceptions: object, *, audited: str = AUDITED) -> int:
    paths = {name: tmp_path / name for name in ("report.json", "audited.txt", "runtime.txt", "exceptions.json")}
    paths["report.json"].write_text(json_dumps(audit_report))
    paths["audited.txt"].write_text(audited)
    paths["runtime.txt"].write_text(RUNTIME)
    paths["exceptions.json"].write_text(json_dumps(exceptions))
    return main([str(path) for path in paths.values()], TODAY)


def test_clean_report_passes(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    assert run(tmp_path, report(), {"exceptions": []}) == 0
    assert capsys.readouterr().out == "Dependency audit passed.\n"


@pytest.mark.parametrize(
    "exceptions",
    [
        {"exceptions": [exception()]},
        {"exceptions": [exception(id="PYSEC-2026-1")]},
        {"exceptions": [exception(package="Pygments")]},
    ],
)
def test_listed_unfixable_development_finding_passes_before_recheck(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], exceptions: dict[str, object]
) -> None:
    audit_report = report(pygments=[finding("PYSEC-2026-1", [], ["GHSA-dev1-0000-0000"])])
    assert run(tmp_path, audit_report, exceptions) == 0
    assert capsys.readouterr().out == (
        "Allowed until 2026-11-12: pygments 2.20.0 PYSEC-2026-1, development only, no fix yet.\nDependency audit passed.\n"
    )


@pytest.mark.parametrize(
    "audit_report,exceptions,message",
    [
        (
            report(anyio=[finding("GHSA-run1-0000-0000", [])]),
            {"exceptions": [exception(id="GHSA-run1-0000-0000", package="anyio")]},
            "anyio 4.14.2 GHSA-run1-0000-0000 affects a shipped runtime dependency. Upgrade it in uv.lock.",
        ),
        (
            report(pygments=[finding("GHSA-dev1-0000-0000", ["2.20.1", "2.21.0"])]),
            {"exceptions": [exception()]},
            "pygments 2.20.0 GHSA-dev1-0000-0000 is fixed in 2.20.1, 2.21.0. Upgrade it in uv.lock.",
        ),
        (
            report(pygments=[finding("GHSA-dev2-0000-0000", [])]),
            {"exceptions": [exception()]},
            "pygments 2.20.0 GHSA-dev2-0000-0000 has no fix. Review it and list it in audit-exceptions.json.",
        ),
        (
            report(pytest=[finding("GHSA-dev1-0000-0000", [])]),
            {"exceptions": [exception()]},
            "pytest 9.0.1 GHSA-dev1-0000-0000 has no fix. Review it and list it in audit-exceptions.json.",
        ),
        (
            report(pygments=[finding("GHSA-dev1-0000-0000", [])]),
            {"exceptions": [exception(recheck="2026-10-13")]},
            "pygments 2.20.0 GHSA-dev1-0000-0000 reached its recheck date 2026-10-13. Review it again.",
        ),
        (
            {
                "dependencies": [
                    *dependencies()[:2],
                    {"name": "Pygments", "version": "2.20.0", "skip_reason": "Not on PyPI"},
                ]
            },
            {"exceptions": []},
            "pip-audit skipped Pygments 2.20.0: Not on PyPI",
        ),
        (
            {"dependencies": dependencies()[:2]},
            {"exceptions": []},
            "pip-audit did not report pygments. Rerun scripts/audit.",
        ),
    ],
)
def test_blocking_findings_fail(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], audit_report: object, exceptions: object, message: str
) -> None:
    assert run(tmp_path, audit_report, exceptions) == 1
    assert capsys.readouterr().err == f"{message}\n"


@pytest.mark.parametrize(
    "exceptions,message",
    [
        ([], "audit-exceptions.json must be an object."),
        ({}, "audit-exceptions.json needs an exceptions list."),
        ({"exceptions": ["GHSA-dev1-0000-0000"]}, "Each audit exception must be an object."),
        ({"exceptions": [exception(id="")]}, "Each audit exception needs an advisory id and a package path."),
        ({"exceptions": [exception(package=" ")]}, "Each audit exception needs an advisory id and a package path."),
        (
            {"exceptions": [exception(reason="unused")]},
            "Exception GHSA-dev1-0000-0000 needs reason 'build-time only' or 'peer dependency provided by the host'.",
        ),
        (
            {"exceptions": [exception(recheck="12/11/2026")]},
            "Exception GHSA-dev1-0000-0000 needs a recheck date as YYYY-MM-DD.",
        ),
        (
            {"exceptions": [exception(recheck=None)]},
            "Exception GHSA-dev1-0000-0000 needs a recheck date as YYYY-MM-DD.",
        ),
        (
            {"exceptions": [exception(recheck="2026-11-13")]},
            "Exception GHSA-dev1-0000-0000 rechecks more than 30 days out. Pick an earlier date.",
        ),
    ],
)
def test_invalid_exceptions_fail(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], exceptions: object, message: str
) -> None:
    assert run(tmp_path, report(), exceptions) == 1
    assert capsys.readouterr().err == f"Dependency audit failed: {message}\n"


MALFORMED_REPORTS: list[tuple[object, str]] = [
    ([], "pip-audit returned no JSON object."),
    ({"fixes": []}, "The pip-audit report lacks its dependency list."),
    ({"dependencies": ["anyio"]}, "The pip-audit report lists an invalid dependency."),
    (
        {"dependencies": [{"name": "anyio", "vulns": []}]},
        "The pip-audit report lists a dependency without a name or version.",
    ),
    ({"dependencies": [{"name": "anyio", "version": "4.14.2"}]}, "pip-audit lists invalid findings for anyio."),
    (
        {"dependencies": [{"name": "anyio", "version": "4.14.2", "vulns": [None]}]},
        "pip-audit lists an invalid finding for anyio.",
    ),
    (report(pytest=[{"fix_versions": []}]), "pip-audit lists a finding without an ID for pytest."),
    (
        report(pytest=[{"id": "GHSA-dev3-0000-0000", "aliases": [1]}]),
        "pip-audit lists invalid aliases for GHSA-dev3-0000-0000.",
    ),
    (
        report(pytest=[{"id": "GHSA-dev3-0000-0000", "fix_versions": "9.0.2"}]),
        "pip-audit lists invalid fixes for GHSA-dev3-0000-0000.",
    ),
]


@pytest.mark.parametrize("audit_report,message", MALFORMED_REPORTS)
def test_malformed_reports_fail(
    tmp_path: Path, capsys: pytest.CaptureFixture[str], audit_report: object, message: str
) -> None:
    assert run(tmp_path, audit_report, {"exceptions": []}) == 1
    assert capsys.readouterr().err == f"Dependency audit failed: {message}\n"


def test_missing_report_fails(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    files = [tmp_path / name for name in ("report.json", "audited.txt", "runtime.txt", "exceptions.json")]
    files[0].write_text("")
    for path in files[1:]:
        path.write_text("{}")
    assert main([str(path) for path in files], TODAY) == 1
    assert capsys.readouterr().err == "pip-audit wrote no report. Fix the error above, then rerun.\n"


def test_missing_exceptions_file_fails(tmp_path: Path, capsys: pytest.CaptureFixture[str]) -> None:
    files = [tmp_path / name for name in ("report.json", "audited.txt", "runtime.txt", "exceptions.json")]
    files[0].write_text(json_dumps(report()))
    assert main([str(path) for path in files], TODAY) == 1
    assert capsys.readouterr().err.startswith("Dependency audit failed: [Errno 2] No such file or directory")


def test_wrong_argument_count_prints_usage(capsys: pytest.CaptureFixture[str]) -> None:
    assert main(["report.json"], TODAY) == 2
    assert capsys.readouterr().err == (
        "Usage: verify_audit.py REPORT_JSON AUDITED_REQUIREMENTS RUNTIME_REQUIREMENTS EXCEPTIONS_JSON\n"
    )
